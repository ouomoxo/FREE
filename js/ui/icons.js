/** Icon path data cache. */
const pathCache = new Map();

/**
 * Merge a rect list into one SVG path string.
 * @param {Rect[]} rects
 */
function toPath(rects) {
  let d = '';
  for (const [x, y, w, h] of rects) {
    d += `M${x} ${y}h${w}v${h}h${-w}z`;
  }
  return d;
}

/**
 * Build an icon element.
 *
 * @param {keyof typeof ICONS} name
 * @param {{size?: number, class?: string, title?: string}} [o]
 * @returns {SVGSVGElement}
 */
export function icon(name, o = {}) {
  const rects = ICONS[name] ?? ICONS.dot;
  let d = pathCache.get(name);
  if (!d) { d = toPath(rects); pathCache.set(name, d); }

  const size = o.size ?? 12;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', `0 0 ${GRID} ${GRID}`);
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('shape-rendering', 'crispEdges');
  svg.setAttribute('focusable', 'false');
  if (o.class) svg.setAttribute('class', o.class);
  if (o.title) {
    svg.setAttribute('role', 'img');
    const t = document.createElementNS('http://www.w3.org/2000/svg', 'title');
    t.textContent = o.title;
    svg.appendChild(t);
  } else {
    svg.setAttribute('aria-hidden', 'true');
  }
  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  path.setAttribute('d', d);
  svg.appendChild(path);
  return svg;
}

